def test_oauth_state_tamper_detection(ig_integration):
    """Verifies that modified nonce, timestamp, or signature fails validation."""
    state = ig_integration.generate_state()
    nonce, ts, sig = state.split(".", 2)

    # Tampered timestamp
    tampered_ts = f"{nonce}.{int(ts)+100}.{sig}"
    assert ig_integration.validate_state(tampered_ts) is False

    # Tampered signature
    tampered_sig = f"{nonce}.{ts}.{sig[:-4]}ffff"
    assert ig_integration.validate_state(tampered_sig) is False


