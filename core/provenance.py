from enum import Enum
from dataclasses import dataclass
from typing import Dict, Any, Tuple, Optional

class LicenseType(str, Enum):
    EDITORIAL_GENERATED = "Editorial Generated"
    CC0 = "CC0"
    PUBLIC_DOMAIN = "Public Domain"
    CC_BY = "CC-BY"
    FAIR_USE = "Fair Use Editorial"

@dataclass
class LegalProvenanceRecord:
    license_type: LicenseType | str
    source_url: Optional[str] = None
    author_or_creator: Optional[str] = None
    verification_notes: Optional[str] = None

    def is_legally_cleared(self) -> bool:
        lic_str = self.license_type.value if isinstance(self.license_type, LicenseType) else str(self.license_type)
        if lic_str not in PERMITTED_LICENSES:
            return False
        rule = PERMITTED_LICENSES[lic_str]
        if rule["requires_attribution"]:
            return bool(self.author_or_creator and self.author_or_creator.strip())
        return True

PERMITTED_LICENSES = {
    "Editorial Generated": {
        "description": "Algorithmic typography and motion graphics generated by SUPER.INTELLIGENCEEE.",
        "commercial_use": True,
        "requires_attribution": False,
        "risk_level": "ZERO"
    },
    "CC0": {
        "description": "Creative Commons Zero - Public Domain Dedication.",
        "commercial_use": True,
        "requires_attribution": False,
        "risk_level": "ZERO"
    },
    "Public Domain": {
        "description": "Uncopyrighted or government technical materials.",
        "commercial_use": True,
        "requires_attribution": False,
        "risk_level": "ZERO"
    },
    "CC-BY": {
        "description": "Creative Commons Attribution 4.0 International.",
        "commercial_use": True,
        "requires_attribution": True,
        "risk_level": "LOW"
    },
    "Fair Use Editorial": {
        "description": "Excerpt for news commentary and journalistic review with source credit.",
        "commercial_use": False,
        "requires_attribution": True,
        "risk_level": "MEDIUM"
    }
}

class ProvenanceManager:
    """Validates source origins and legal licensing for media and claims."""

    @classmethod
    def validate_license(cls, license_name: str, attribution: str = "") -> Tuple[bool, str]:
        if license_name not in PERMITTED_LICENSES:
            return False, f"Unauthorized license: '{license_name}'. Permitted: {list(PERMITTED_LICENSES.keys())}"
        
        rule = PERMITTED_LICENSES[license_name]
        if rule["requires_attribution"] and not attribution.strip():
            return False, f"License '{license_name}' requires explicit creator attribution."

        return True, f"License validated: {license_name}"

    @classmethod
    def build_record(
        cls,
        filename: str,
        source_url: str,
        creator: str,
        license_name: str,
        attribution: str = ""
    ) -> Dict[str, Any]:
        valid, msg = cls.validate_license(license_name, attribution)
        if not valid:
            raise ValueError(f"Provenance violation: {msg}")

        return {
            "filename": filename,
            "source_url": source_url or "https://super.intelligenceee.local",
            "creator": creator or "SUPER.INTELLIGENCEEE",
            "license": license_name,
            "attribution": attribution,
            "permissions": "Full Editorial Rights Authorized",
            "risk_level": PERMITTED_LICENSES[license_name]["risk_level"]
        }
